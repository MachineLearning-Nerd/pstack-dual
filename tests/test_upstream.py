from __future__ import annotations

import hashlib
import importlib.util
import json
from pathlib import Path
import subprocess
import sys
import tempfile
import unittest


SPEC = importlib.util.spec_from_file_location(
    'check_upstream', Path(__file__).resolve().parents[1] / 'tools/check_upstream.py')
CHECK = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(CHECK)


class UpstreamAuditTests(unittest.TestCase):
    def setUp(self):
        self.temporary = tempfile.TemporaryDirectory()
        self.addCleanup(self.temporary.cleanup)
        self.root = Path(self.temporary.name)
        (self.root / 'upstream').mkdir()
        self.reviews = {'version': 1, 'reviews': {}, 'additions': []}
        self.write('docs/evidence.md', 'Reviewed for host compatibility.')

    def write(self, relative, content):
        path = self.root / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content)
        return path

    def source(self, relative, content='Original source'):
        return self.write('upstream/' + relative, content)

    def lock(self):
        return {'commit': '0' * 40, 'pstack_version': '1.0.0',
                'repository': 'https://github.com/cursor/plugins.git', 'files': {
            path.relative_to(self.root / 'upstream').as_posix():
                hashlib.sha256(path.read_bytes()).hexdigest()
            for path in (self.root / 'upstream').rglob('*') if path.is_file()}}

    def review(self, source, disposition):
        self.reviews['reviews'][source] = {
            'sha256': hashlib.sha256((self.root / 'upstream' / source).read_bytes()).hexdigest(),
            'disposition': disposition, 'reason': 'Preserves native host behavior.',
            'evidence': ['docs/evidence.md']}

    def audit(self, **kwargs):
        return CHECK.audit(self.root, lock=self.lock(), reviews=self.reviews, **kwargs)

    def assert_error(self, result, text):
        self.assertFalse(result['valid'], result)
        self.assertTrue(any(text in error for error in result['errors']), result)

    def test_new_skill_and_nested_script_are_accounted_for(self):
        self.source('pstack/skills/new/SKILL.md', 'New instructions')
        self.source('pstack/skills/new/scripts/run.py', 'print(42)')
        self.write('skills/new/SKILL.md', 'Adapted instructions')
        self.write('skills/new/scripts/run.py', 'print(42)')
        result = self.audit()
        self.assertTrue(result['valid'], result)
        self.assertEqual(len(result['files']), 2)
        (self.root / 'skills/new/scripts/run.py').unlink()
        self.assert_error(self.audit(), 'missing generated')

    def test_wrong_script_bytes_fail(self):
        self.source('pstack/skills/new/scripts/run.py', 'print(42)')
        self.write('skills/new/scripts/run.py', 'print(0)')
        self.assert_error(self.audit(), 'generated bytes differ')

    def test_historical_host_adapter_changes_require_reconciliation(self):
        source = 'pstack/docs/harness/claude-code.md'
        self.source(source, 'Upstream host mechanics')
        self.write('docs/harness/claude-code.md', 'Historical reference, portable harness takes precedence.')
        self.assert_error(self.audit(), 'review required')
        self.review(source, 'dormant-reference')
        self.assertTrue(self.audit()['valid'])
        self.source(source, 'New upstream host capability')
        self.assert_error(self.audit(), 'review hash differs')

    def test_manifest_and_lock_version_must_agree(self):
        source = 'pstack/plugin.json'
        self.source(source, json.dumps({'version': '1.0.0'}))
        self.review(source, 'source-only')
        self.assertTrue(self.audit()['valid'])
        lock = self.lock()
        lock['pstack_version'] = '2.0.0'
        self.assert_error(CHECK.audit(self.root, lock=lock, reviews=self.reviews),
                          'manifest version differs')

    def test_mutable_reference_is_not_an_immutable_pin(self):
        lock = self.lock()
        lock['commit'] = 'main'
        self.assert_error(CHECK.audit(self.root, lock=lock, reviews=self.reviews),
                          'full lowercase commit')

    def test_changed_override_source_requires_fresh_review_even_with_new_lock(self):
        source = 'pstack/skills/how/SKILL.md'
        self.source(source)
        self.write('overrides/how/SKILL.md', 'Host override')
        self.write('skills/how/SKILL.md', 'Host override')
        self.assert_error(self.audit(), 'review required')
        self.review(source, 'overridden')
        self.assertTrue(self.audit()['valid'])
        self.source(source, 'Upstream improvement now hidden by the override')
        self.assert_error(self.audit(), 'review hash differs')

    def test_nested_override_and_removed_source_are_detected(self):
        source = 'pstack/skills/poteto-mode/playbooks/feature.md'
        self.source(source)
        self.write('overrides/poteto-mode/playbooks/feature.md', 'Override')
        self.write('skills/poteto-mode/playbooks/feature.md', 'Override')
        self.review(source, 'overridden')
        self.assertTrue(self.audit()['valid'])
        (self.root / 'upstream' / source).unlink()
        result = self.audit()
        self.assert_error(result, 'orphan override')
        self.assert_error(result, 'stale review')

    def test_synthesized_mode_requires_current_source_review(self):
        source = 'pstack/skills/poteto-mode/SKILL.md'
        self.source(source)
        self.write('skills/poteto-mode/SKILL.md', 'Synthesized mode')
        self.review(source, 'synthesized')
        self.assertTrue(self.audit()['valid'])
        self.source(source, 'New upstream delegation rule')
        self.assert_error(self.audit(), 'review hash differs')

    def test_unknown_source_and_new_agent_require_explicit_source_only_review(self):
        for source in ['pstack/new-surface/instructions.md', 'pstack/agents/new-reviewer.md']:
            with self.subTest(source=source):
                self.source(source)
                self.assert_error(self.audit(), 'review required')
                self.review(source, 'source-only')
                self.assertTrue(self.audit()['valid'])

    def test_generated_metadata_and_license_collisions_require_review(self):
        for tail in ['LICENSE', 'agents/openai.yaml']:
            with self.subTest(tail=tail):
                source = 'pstack/skills/new/' + tail
                self.source(source)
                self.write('skills/new/' + tail, 'Generated content')
                self.assert_error(self.audit(), 'review required')
                self.review(source, 'synthesized')
                self.assertTrue(self.audit()['valid'])

    def test_all_routes_and_dormant_automation(self):
        routes = {
            'cursor-team-kit/skills/control-cli/scripts/probe.py': 'skills/control-cli/scripts/probe.py',
            'pstack/docs/guide/setup.md': 'docs/guide/setup.md',
            'pstack/docs/harness/test.md': 'docs/harness/test.md',
            'pstack/assets/image.svg': 'assets/image.svg',
            'pstack/agents/comment-sicko.md': 'skills/pstack-harness/references/comment-sicko.md',
            'pstack/automations/job/config.yaml': 'automations/job/config.yaml',
        }
        for source, target in routes.items():
            self.source(source)
            self.write(target, 'Original source')
        self.assert_error(self.audit(), 'review required')
        self.review('pstack/automations/job/config.yaml', 'dormant-reference')
        self.review('pstack/docs/harness/test.md', 'dormant-reference')
        result = self.audit()
        self.assertTrue(result['valid'], result)
        self.assertEqual({row['source']: row['target'] for row in result['files']}, routes)
        self.write('skills/pstack-harness/references/comment-sicko.md', 'Altered persona')
        self.assert_error(self.audit(), 'generated bytes differ')

    def test_wrong_disposition_and_missing_evidence_fail(self):
        source = 'pstack/skills/how/SKILL.md'
        self.source(source)
        self.write('overrides/how/SKILL.md', 'Override')
        self.review(source, 'source-only')
        self.assert_error(self.audit(check_generated=False), 'disposition')
        self.review(source, 'overridden')
        self.reviews['reviews'][source]['evidence'] = ['missing.md']
        self.assert_error(self.audit(check_generated=False), 'evidence')
        self.reviews['reviews'][source]['evidence'] = ['../outside.md']
        self.assert_error(self.audit(check_generated=False), 'unsafe')

    def test_additions_allow_only_exact_existing_override_paths(self):
        self.write('overrides/pstack-harness/SKILL.md', 'Native harness')
        self.assert_error(self.audit(check_generated=False), 'orphan override')
        self.reviews['additions'] = ['pstack-harness/SKILL.md']
        self.assertTrue(self.audit(check_generated=False)['valid'])
        self.reviews['additions'].append('missing/SKILL.md')
        self.assert_error(self.audit(check_generated=False), 'stale addition')

    def test_lock_mismatch_and_unsafe_paths_fail(self):
        self.source('pstack/skills/how/SKILL.md')
        self.assert_error(CHECK.audit(self.root, lock={'files': {}}, reviews=self.reviews,
                                      check_generated=False), 'snapshot differs')
        self.assert_error(CHECK.audit(self.root, lock={'files': {'../escape': 'a' * 64}},
                                      reviews=self.reviews, check_generated=False), 'unsafe')

    def test_malformed_policy_is_invalid_instead_of_crashing(self):
        for policy in [[], {'version': 2}, {'version': 1, 'reviews': [], 'additions': []},
                       {'version': 1, 'reviews': {}, 'additions': [42]},
                       {'version': 1, 'reviews': {'pstack/README.md': None}, 'additions': []},
                       {'version': 1, 'reviews': {'pstack/README.md': {'disposition': []}},
                        'additions': []}]:
            with self.subTest(policy=policy):
                result = CHECK.audit(self.root, lock={'files': {}}, reviews=policy,
                                     check_generated=False)
                self.assertFalse(result['valid'], result)

    def test_nested_example_metadata_is_copied_without_review(self):
        for tail in ['examples/LICENSE', 'examples/agents/openai.yaml']:
            self.source('pstack/skills/new/' + tail)
            self.write('skills/new/' + tail, 'Original source')
        self.assertTrue(self.audit()['valid'])

    def test_snapshot_and_generated_symlinks_are_rejected(self):
        source = 'pstack/skills/new/run.py'
        original = self.source(source, 'print(42)')
        generated = self.write('skills/new/run.py', 'print(42)')
        external = self.root.parent / (self.root.name + '-outside')
        external.write_text('print(42)')
        self.addCleanup(external.unlink)
        generated.unlink()
        generated.symlink_to(external)
        self.assert_error(self.audit(), 'external generated')
        generated.unlink()
        generated.write_text('print(42)')
        original.unlink()
        original.symlink_to(external)
        self.assert_error(self.audit(), 'snapshot symlink')

    def test_cli_accepts_reviewed_policy_and_no_generated_preflight(self):
        source = 'pstack/agents/poteto-agent.md'
        self.source(source)
        self.review(source, 'synthesized')
        self.write('upstream.lock.json', json.dumps(self.lock()))
        self.write('upstream-reviews.json', json.dumps(self.reviews))
        result = subprocess.run([sys.executable, str(Path(CHECK.__file__)), '--root',
                                 str(self.root), '--no-generated'], text=True, capture_output=True)
        self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
        self.assertIn('VERIFIED: 1 source files; 1 reviews; 0 errors', result.stdout)

    def test_cli_json_is_deterministic_and_has_failing_exit_status(self):
        self.source('pstack/unrecognized.md')
        self.write('upstream.lock.json', json.dumps(self.lock()))
        self.write('upstream-reviews.json', json.dumps(self.reviews))
        command = [sys.executable, str(Path(CHECK.__file__)), '--root', str(self.root),
                   '--json', '--no-generated']
        first = subprocess.run(command, text=True, capture_output=True)
        second = subprocess.run(command, text=True, capture_output=True)
        self.assertEqual(first.returncode, 1)
        self.assertEqual(first.stdout, second.stdout)
        self.assertFalse(json.loads(first.stdout)['valid'])


if __name__ == '__main__':
    unittest.main()
